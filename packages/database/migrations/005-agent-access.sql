DO $$ BEGIN
 IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='personal_context_reader') THEN CREATE ROLE personal_context_reader NOLOGIN; END IF;
 IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='personal_context_audit') THEN CREATE ROLE personal_context_audit NOLOGIN; END IF;
END $$;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO personal_context_reader,personal_context_audit;
CREATE FUNCTION can_read_account(account uuid) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
 SELECT EXISTS(SELECT 1 FROM access_grants g JOIN agent_clients c ON c.id=g.client_id
 WHERE g.account_id=account AND c.revoked_at IS NULL AND c.id=nullif(current_setting('app.client_id',true),'')::uuid)
$$;
REVOKE ALL ON FUNCTION can_read_account(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION can_read_account(uuid) TO personal_context_reader;
